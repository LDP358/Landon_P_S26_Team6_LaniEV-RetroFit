function verify_x_sensor_tracker()
%VERIFY_X_SENSOR_TRACKER Run controlled scenarios WITHOUT opening the GUI.
% Uses same sensor rays, feedback controller and moving-actuator kinematics.
% This is numerical model verification, NOT physical hardware certification.

cfg=x_sensor_core('config');
ref=x_sensor_core('init',cfg);
assert(x_sensor_core('safe',ref.angles,cfg),'Initial pose unsafe');
assert(all(abs(ref.lengths/.0254 - 12)<1e-7), ...
    'Neutral actuator lengths must each equal the 12-inch frame gap.');
assert(~cfg.physicalActuatorSelected, ...
    'This version must not claim the hypothetical actuators are real hardware.');
assert(all(all(abs(cfg.lowerMounts(1:2,:)-cfg.upperMounts(1:2,:))<1e-9)), ...
    'Lower and upper actuator mounts must align at the edge midpoints.');
assert(all(abs(cfg.lowerMounts(3,:))<1e-9), ...
    'Lower actuator mounts must be in the lower-frame rim plane.');
assert(all(abs(cfg.actStrokeM-(cfg.actMaxLength-cfg.actMinLength))<1e-9), ...
    'The virtual stroke is inconsistent with its min/max pin distances.');
% Verify signed axial forces from gravity using the ACTUAL geometry.
% At level, zero gravity torque and zero axial gravity load is expected.
flatLoads=x_sensor_core('forces',[0;0],cfg);
assert(max(abs(flatLoads.forceLbf))<1e-10, ...
    'Level frame must have zero gravity-induced actuator moment load.');
loads88=x_sensor_core('forces',deg2rad([8;8]),cfg);
assert(all(abs(abs(loads88.forceLbf)-[1.395973;1.967919])<0.02), ...
    'Static gravity force at 8/8 tilt is inconsistent with frame geometry.');
assert(max(abs(loads88.residualMomentNm(1:2)))<1e-8, ...
    'Actuator forces must balance x/y gravitational moments.');
assert(all(isfinite(loads88.forceN)), ...
    'Computed forces must be finite.');
assert(abs(cfg.panelEW/0.0254-48)<1e-8 && ...
       abs(cfg.panelNS/0.0254-68)<1e-8, ...
    'Model must use the newly measured 48 by 68 inch panel.');
assert(cfg.maxPitchDeg == 8 && cfg.maxRollDeg == 8, ...
    'Tilt limits must equal +/-8 degrees.');
assert(all(abs(cfg.upperMounts(1:2,1)-[0;cfg.panelNS/2])<1e-9), ...
    'North actuator is not at the midpoint of the north edge.');
assert(all(abs(cfg.upperMounts(1:2,2)-[-cfg.panelEW/2;0])<1e-9), ...
    'West actuator is not at the midpoint of the west edge.');
assert(all(abs(cfg.elbowUpperMounts(1:2,1)-[0;-cfg.panelNS/2])<1e-9), ...
    'South elbow is not at midpoint of south edge.');
assert(all(abs(cfg.elbowUpperMounts(1:2,2)-[cfg.panelEW/2;0])<1e-9), ...
    'East elbow is not at midpoint of east edge.');
% Full simultaneous ±8-degree envelope; verifies BOTH independent motions.
allLengths=[];
for pitchDeg=-8:0.25:8
    for rollDeg=-8:0.25:8
        th=deg2rad([pitchDeg;rollDeg]);
        allLengths(end+1,:)=x_sensor_core('lengths',th,cfg).'/0.0254; %#ok<AGROW>
    end
end
minRequired=min(allLengths,[],1).';
maxRequired=max(allLengths,[],1).';
strokeRequired=maxRequired-minRequired;
fprintf('Outer-rim centered lower + upper mounts (pin-to-pin):\n');
fprintf('  North: %.3f–%.3f in, minimum stroke %.3f in\n', ...
    minRequired(1),maxRequired(1),strokeRequired(1));
fprintf('  West:  %.3f–%.3f in, minimum stroke %.3f in\n', ...
    minRequired(2),maxRequired(2),strokeRequired(2));
fprintf('  Virtual envelopes N %.2f–%.2f, W %.2f–%.2f in\n', ...
    cfg.actMinLength(1)/0.0254,cfg.actMaxLength(1)/0.0254, ...
    cfg.actMinLength(2)/0.0254,cfg.actMaxLength(2)/0.0254);
assert(all(minRequired >= cfg.actMinLength/0.0254), ...
    'At least one virtual actuator cannot retract far enough.');
assert(all(maxRequired <= cfg.actMaxLength/0.0254), ...
    'At least one virtual actuator cannot extend far enough.');
assert(all(abs(minRequired-[7.217548;8.604823])<0.025), ...
    'Lower actuator length targets changed unexpectedly.');
assert(all(abs(maxRequired-[16.714209;15.319079])<0.025), ...
    'Upper actuator length targets changed unexpectedly.');
assert(all(abs(strokeRequired-[9.496661;6.714257])<0.05), ...
    'Expected actuator travel changed unexpectedly.');
assert(all(abs(cfg.elbowUpperMounts(1:2,1)-[0;-34*0.0254])<1e-9), ...
    'South elbow is incorrectly located.');
assert(all(abs(cfg.elbowUpperMounts(1:2,2)-[24*0.0254;0])<1e-9), ...
    'East elbow is incorrectly located.');
assert(abs(cfg.sensorBoardHeight - cfg.sensorBoardWidth*68/48)<1e-10, ...
    'X sensor diagram aspect ratio did not update.');
for p=-8:2:8
    for r=-8:2:8
        theta=deg2rad([p;r]);
        assert(x_sensor_core('safe',theta,cfg), ...
            'Specified tilt envelope has an unsafe configuration.');
        [pts,reach]=x_sensor_core('elbows',theta,cfg);
        assert(all(reach),'Elbow linkage is overextended.');
        for k=1:2
            lower=norm(pts(:,2,k)-pts(:,1,k));
            upper=norm(pts(:,3,k)-pts(:,2,k));
            assert(abs(lower-cfg.elbowLinkLength(k))<1e-7 && ...
                abs(upper-cfg.elbowLinkLength(k))<1e-7, ...
                'Elbow segments did not maintain fixed length.');
        end
    end
end
vertical=x_sensor_core('sense',[0;0],0,90,cfg);
assert(max(abs(vertical.error))<1e-10, ...
    'Perfectly overhead sun should balance all four sensors.');

g=x_sensor_core('sense',[0;0],315,82,cfg);
assert(g.error(1)>0 && g.error(2)>0, ...
    'Northwest sun should make the north and west readings larger.');

scenarios=[315 82;45 82;90 82;180 82;0 90];
for c=1:size(scenarios,1)
    az=scenarios(c,1);el=scenarios(c,2);
    state=x_sensor_core('init',cfg);
    normSun=x_sensor_core('sunvec',az,el);
    n0=x_sensor_core('rotation',state.angles)*[0;0;1];
    initialError=acosd(max(-1,min(1,dot(normSun,n0))));
    maxDuration=80;dt=cfg.demoDtSeconds;
    for j=1:round(maxDuration/dt)
        old=state;
        state=x_sensor_core('step',state,cfg,az,el,dt);
        assert(all(isfinite(state.load.forceLbf)), ...
            'Actuator force calculation failed.');
        assert(all(state.currentA>=0) && all(isfinite(state.currentA)), ...
            'Illustrative motor current must be finite and nonnegative.');
        assert(all(state.currentA(abs(state.lengths-old.lengths)<1e-10) == ...
                   cfg.assumedHoldCurrentA(abs(state.lengths-old.lengths)<1e-10)), ...
            'Stationary motors should draw the configured resting current.');
        assert(all(state.peakCurrentA>=state.currentA-1e-10), ...
            'Modeled peak current cannot fall below its step average.');
        assert(all(state.movementDuty>=0 & state.movementDuty<=1+1e-10), ...
            'Motor duty during a simulation step must lie in [0,1].');
        assert(all(state.loadCurrentContributionA>=0), ...
            'Conservative gravity load contribution cannot be negative.');
        assert(all(state.startCurrentContributionA>=0), ...
            'Assumed startup average current must be nonnegative.');
        if any(abs(state.lengths-old.lengths)>1e-10)
            assert(all(state.currentA>=0), ...
                'Estimated step-averaged current must be nonnegative.');
        end
        assert(state.batteryEnergyWh>=old.batteryEnergyWh, ...
            'Estimated total battery energy cannot decrease.');
        assert(x_sensor_core('safe',state.angles,cfg), ...
            'Unsafe pose at scenario %d iteration %d',c,j);
        assert(all(abs(state.lengths-old.lengths)<=cfg.actSpeed*dt+1e-7), ...
            'Actuator motion too fast.');
        assert(state.minCornerM>=cfg.minPanelHeight-1e-7, ...
            'Panel struck lower frame.');
        assert(all(state.lengths>=cfg.actMinLength-1e-7) && ...
               all(state.lengths<=cfg.actMaxLength+1e-7), ...
            'Actuator stroke limit exceeded.');
    end
    finalError=state.pointingErrorDeg;
    fprintf('Sun %3.0f az / %2.0f el: pointing %.2f --> %.2f deg | ', ...
        az,el,initialError,finalError);
    fprintf('pitch %+.2f, roll %+.2f deg\n',rad2deg(state.angles));
    if initialError>0.1
        assert(finalError<initialError-1, ...
            'Sensor-based tracking did not appreciably improve pointing.');
        assert(finalError<4.5, ...
            'Sensor-based pointing error too large for a high-elevation test.');
    else
        assert(norm(state.angles)<1e-8, ...
            'Overhead light should keep the panel level.');
    end
end
fprintf('\nAll sensor, convergence, geometry and illustrative-current checks passed.\n');
fprintf(['All short actuator dimensions are VIRTUAL geometry targets, ', ...
    'not commercially selected hardware.\n']);
fprintf(['These tests check ideal elbow LINK LENGTHS only. They do NOT ', ...
    'validate actual hinge axes, yaw stability, wind, collisions, ', ...
    'real motor currents, sensor calibration, or hardware feedback.\n']);
end
